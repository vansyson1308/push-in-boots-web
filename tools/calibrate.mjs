// Sets each stage's third-star score from a playthrough by the rule-based bot, so that the
// target is always something that has actually been achieved.   node tools/calibrate.mjs
import fs from 'node:fs';
import { data, runBot } from '../tests/harness.mjs';

const out = {};
for (const id of data.order) {
  const st = data.stages[id];
  let best = 0;
  for (const viewW of [14, 16, 18.5]) {
    const r = runBot(st, { mode: 'story', viewW, maxSeconds: 400 });
    if (r.outcome !== 'win') throw new Error(`bot could not finish ${id} at view width ${viewW}`);
    const s = r.sim;
    const total = s.score + Math.max(0, Math.round((st.par_seconds - s.time) * 20)) + (s.kos === 0 ? 1500 : 0);
    best = Math.max(best, total);
    console.log(id, 'view', viewW, 'score', s.score, 'total', total, 'time', s.time.toFixed(0), 'chain', s.chain.best, 'kos', s.kos);
  }
  out[id] = Math.round((best * 0.9) / 500) * 500;
}
fs.writeFileSync(new URL('../src/targets.js', import.meta.url),
  `// Generated by tools/calibrate.mjs: 90% of the best score the bot reached on each stage.\nexport const TARGETS = ${JSON.stringify(out, null, 2)};\n`);
console.log(out);
